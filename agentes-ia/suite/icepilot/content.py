ALIASES = {"snakes": "quiz"}


def pack_items(pack, game, lang, columns):
    """Filas del paquete para un juego, como diccionarios {columna: valor}."""
    data = PACKS[pack].get(lang) or PACKS[pack]["es"]
    rows = data.get(game) or data.get(ALIASES.get(game, ""), [])
    if game == "truths" and not rows:
        rows = TEAM.get(lang, TEAM["es"])["truths"]
    if game == "snakes":
        rows = [r[:6] for r in rows]
    return [dict(zip(columns, (str(v) for v in row))) for row in rows]


def pack_titles(pack, lang):
    data = PACKS[pack].get(lang) or PACKS[pack]["es"]
    return data["title"], data["subtitle"]
